using System.Text.Json;
using Cabinet.Agent.Contracts;

namespace Cabinet.Agent.Core;

/// <summary>Reads the local protected configuration, validated against agent/agent-config.schema.json.</summary>
public static class AgentConfigLoader
{
    public const int MaxBytes = 64 * 1024;

    public static AgentConfig Load(string path) => Load(path, File.ReadAllBytes);

    /// <summary>
    /// <paramref name="read"/> is replaceable for tests. A file that exists but cannot be read is refused like any other bad
    /// configuration, so the service logs why before it stops. Rewriting the file with an editor drops the permissions the
    /// installer set, and the network service then cannot open it (2026-10-30 hardware test: the service died with no log line).
    /// </summary>
    internal static AgentConfig Load(string path, Func<string, byte[]> read)
    {
        var info = new FileInfo(path);
        if (!info.Exists) throw new AgentConfigException("The agent configuration file does not exist.");
        if (info.Length > MaxBytes) throw new AgentConfigException("The agent configuration file is too large.");
        byte[] bytes;
        try { bytes = read(path); }
        catch (UnauthorizedAccessException)
        {
            throw new AgentConfigException("The agent configuration file cannot be read: access is denied. Its permissions were probably " +
                "changed by editing it by hand. Run the installer again to restore them; do not edit this file directly.");
        }
        catch (IOException e)
        {
            throw new AgentConfigException($"The agent configuration file cannot be read: {e.GetType().Name}.");
        }
        return Parse(bytes);
    }

    public static AgentConfig Parse(byte[] utf8)
    {
        if (!StrictJson.TryParse(utf8, MaxBytes, out JsonDocument? doc))
            throw new AgentConfigException("The agent configuration is not valid JSON.");
        using (doc)
        {
            IReadOnlyList<SchemaIssue> issues = ContractSchemas.Instance.Validate(ContractSchemas.Local("agent-config"), doc!.RootElement);
            if (issues.Count > 0)
                throw new AgentConfigException("The agent configuration does not match its schema: " +
                    string.Join(", ", issues.Select(i => $"{i.Path} ({i.Rule})")));
            return doc.RootElement.Deserialize<AgentConfig>(ContractJson.Options)!;
        }
    }
}

public sealed class AgentConfigException(string message) : Exception(message);
