import { randomBytes, randomUUID } from "node:crypto";
import { createTestDatabase } from "./dist/test/database.js";
import { buildConsoleApi } from "./dist/src/console-api/server.js";
import { ResultStream } from "./dist/src/console-api/stream.js";
import { SecretBox } from "./dist/src/auth/secrets.js";
import { hashPassword } from "./dist/src/auth/passwords.js";
import * as totp from "./dist/src/auth/totp.js";
import { developmentIssuingKey } from "./dist/src/pki/issuing.js";
import { enableDemo, DemoSimulator } from "./dist/src/demo/demo.js";
import { tempDir } from "./dist/test/helpers.js";
import { createServer } from "node:net";
import { chromium } from "playwright";

const port = await new Promise(r => { const s = createServer(); s.listen(0, "127.0.0.1", () => { const p = s.address().port; s.close(() => r(p)); }); });
const origin = `http://127.0.0.1:${port}`;
const db = await createTestDatabase();
let clock = Date.now();
const secrets = new SecretBox(randomBytes(32).toString("base64"));
const stream = new ResultStream(db.appUrl, db.app); await stream.start();
const app = await buildConsoleApi({ pool: db.app, secrets, issuingKey: await developmentIssuingKey(tempDir()), origin, stream, staticDir: "../console/dist", logger: false, now: () => clock });
await app.listen({ host: "127.0.0.1", port });
const pw = "correct horse battery staple", sec = totp.newSecret(), id = randomUUID();
await db.app.query(`INSERT INTO users (id, username, name, role, password_hash, must_change_password, totp_enabled, totp_secret_enc, tour_completed) VALUES ($1,'ada.admin','Ada Admin','admin',$2,false,true,$3,true)`, [id, await hashPassword(pw), secrets.seal(sec)]);
await enableDemo(db.app, id);
const sim = new DemoSimulator(db.app, m => console.error(m)); sim.start();
const browser = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium" });
const ctx = await browser.newContext({ viewport: { width: 1360, height: 900 } });
const page = await ctx.newPage();
const out = process.argv[2] ?? "/tmp/shots";
const texts = [];
const shot = async (name) => { await page.waitForTimeout(3000); await page.screenshot({ path: `${out}/${name}.png`, fullPage: true }); texts.push(`=== ${name} (${page.url().replace(origin, "")})\n` + (await page.locator("body").innerText())); };
await page.goto(origin); await page.getByLabel("Username").waitFor(); await shot("00-signin");
await page.getByLabel("Username").fill("ada.admin"); await page.getByLabel("Password").fill(pw);
await page.getByRole("button", { name: "Sign in" }).click();
await page.getByLabel(/6-digit code/).waitFor(); await shot("01-code");
clock += 30000; await page.getByLabel(/6-digit code/).fill(totp.code(sec, totp.stepAt(clock)));
await page.getByRole("button", { name: "Continue" }).click();
await page.getByRole("heading", { name: "Fleet", level: 1 }).waitFor();
const cab = (await db.app.query("SELECT id FROM cabinets WHERE demo_scenario IS NOT NULL ORDER BY name LIMIT 1")).rows[0].id;
const site = (await db.app.query("SELECT site_id FROM cabinets WHERE id = $1", [cab])).rows[0].site_id;
const client = (await db.app.query("SELECT client_id FROM sites WHERE id = $1", [site])).rows[0].client_id;
const routes = ["/", `/clients/${client}`, `/sites/${site}`, "/alerts", "/issues", "/incidents", "/fleet-operations", "/account", "/demo",
  "/admin", "/admin/setup", "/admin/pending", "/admin/tokens", "/admin/scanner", "/admin/audit", "/admin/software", "/admin/upgrades", "/admin/users", "/admin/online", "/admin/clients", "/admin/issues", "/admin/safety", "/admin/security", "/admin/settings"];
for (const s of ["overview","alerts","crashes","events","scanner","devices","updates","time","drives","network","firewall","services","processes","software","files","history"]) routes.push(`/cabinets/${cab}/${s}`);
let n = 2;
for (const r of routes) { await page.goto(origin + r); await shot(String(n++).padStart(2, "0") + "-" + (r.replace(/[0-9a-f-]{36}/g, "ID").replace(/\W+/g, "_") || "home")); }
import { writeFileSync } from "node:fs";
writeFileSync(`${out}/all-text.txt`, texts.join("\n\n"));
sim.stop(); await browser.close(); await app.close(); await stream.stop(); await db.drop();
console.log("done", n);
